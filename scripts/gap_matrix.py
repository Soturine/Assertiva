"""The gap ledgers: validate each JSON (source of truth) and render its Markdown view.

    python scripts/gap_matrix.py            # validate and rewrite every view
    python scripts/gap_matrix.py --check    # validate only; exit 1 when a JSON or a rendered view is stale

Two ledgers: POST_DOGFOOD_GAP_MATRIX (the 0.10.0 round, a historical record: its rows are not rewritten) and
REMEDIATION_0_10_1 (the post-release Derivanta dogfood findings AXF-*, and the DG-* discoveries made while fixing
them; each row also carries the checkpoint, where it came from and the triage decision).

Rules enforced here, not by convention: every inherited ID is present exactly once; a status is one of STATUSES;
FIXED and PARTIAL name the commit and the before/after tests; DUPLICATE_OF names an existing ID; BLOCKED, NOT_RUN,
ACCEPTED_LIMITATION and REJECTED_WITH_EVIDENCE give the reason in ``limitations``.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs" / "assurance" / "POST_DOGFOOD_GAP_MATRIX.json"
VIEW = ROOT / "docs" / "assurance" / "POST_DOGFOOD_GAP_MATRIX.md"
REMEDIATION_DATA = ROOT / "docs" / "assurance" / "REMEDIATION_0_10_1.json"
REMEDIATION_VIEW = ROOT / "docs" / "assurance" / "REMEDIATION_0_10_1.md"
STATUSES = ("NEW", "REPRODUCED", "DUPLICATE_OF", "FIXED", "PARTIAL", "ALREADY_FIXED_VERIFIED", "ACCEPTED_LIMITATION",
            "BLOCKED", "NOT_RUN", "REJECTED_WITH_EVIDENCE")
INHERITED = ([f"TCC-A{i:02d}" for i in range(1, 25)] + [f"AX-E{i:02d}" for i in range(1, 7)]
             + [f"AG-{i:02d}" for i in range(1, 14)])
FIELDS = ("id", "source", "pr_url", "revision_evidence", "failure_reproducer", "stack", "severity", "root_cause",
          "shared_root_cause_ids", "layer", "risk", "test_before", "test_after", "negative_controls", "metrics", "owner",
          "commit_fixed", "status", "limitations", "release_gate")


REMEDIATION_INHERITED = [f"AXF-{i:02d}" for i in range(1, 9)] + ["AXF-M2-01", "AXF-M3-01", "AXF-M3-02"]
REMEDIATION_FIELDS = ("checkpoint", "origin", "expected", "observed", "decision")
DECISIONS = ("FIX_NOW", "FIX_IN_NEXT_CYCLE", "RESEARCH", "ACCEPT_LIMITATION", "REJECT")


def problems(rows: list[dict], inherited=INHERITED, fields=FIELDS) -> list[str]:
    out, ids = [], [r.get("id") for r in rows]
    out += [f"missing inherited id {i}" for i in inherited if i not in ids]
    out += [f"duplicate id {i}" for i in sorted({i for i in ids if ids.count(i) > 1})]
    for row in rows:
        rid = row.get("id")
        out += [f"{rid}: missing field {f}" for f in fields if f not in row]
        if "decision" in fields and row.get("decision") not in DECISIONS:
            out.append(f"{rid}: decision {row.get('decision')!r} is not one of {', '.join(DECISIONS)}")
        if row.get("decision") in ("FIX_IN_NEXT_CYCLE", "RESEARCH") and not row.get("next"):
            out.append(f"{rid}: a deferred row says what would settle it in next")
        status = row.get("status")
        if status not in STATUSES:
            out.append(f"{rid}: status {status!r} is not one of {', '.join(STATUSES)}")
        if status in ("FIXED", "PARTIAL") and not (row.get("commit_fixed") and row.get("test_before") and row.get("test_after")):
            out.append(f"{rid}: {status} needs commit_fixed, test_before and test_after")
        if status == "DUPLICATE_OF" and not set(row.get("shared_root_cause_ids") or []) & set(ids):
            out.append(f"{rid}: DUPLICATE_OF needs the id it duplicates in shared_root_cause_ids")
        if status == "ALREADY_FIXED_VERIFIED" and not row.get("test_before"):
            out.append(f"{rid}: ALREADY_FIXED_VERIFIED needs the test that verifies it in test_before")
        if status in ("NEW", "BLOCKED", "NOT_RUN", "ACCEPTED_LIMITATION", "REJECTED_WITH_EVIDENCE", "PARTIAL") and not row.get("limitations"):
            out.append(f"{rid}: {status} needs its reason in limitations")
    return out


def render(rows: list[dict]) -> str:
    counts = {s: sum(r["status"] == s for r in rows) for s in STATUSES}
    lines = [
        "# Post-dogfood gap matrix",
        "",
        (f"Generated by [`scripts/gap_matrix.py`](../../scripts/gap_matrix.py) from [the JSON](POST_DOGFOOD_GAP_MATRIX.json) "
        "(the source of truth; edit it, then re-run the script). "
        f"{len(rows)} rows: {len(INHERITED)} inherited IDs (TCC-A01..A24, AX-E01..E06, AG-01..AG-13; never renumbered) "
        "plus gaps found in this audit."),
        "",
        "Status counts: " + ", ".join(f"{s} {n}" for s, n in counts.items() if n) + ".",
        "",
        "| ID | Source | Severity | Layer / owner | Status | Commit | Root cause | Tests (before → after) | Shared cause | Limitations |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    cell = lambda v: (", ".join(v) if isinstance(v, list) else str(v or "")).replace("|", "\\|").replace("\n", " ")
    for r in rows:
        tests = f"{cell(r['test_before'])} → {cell(r['test_after'])}" if r["test_before"] or r["test_after"] else ""
        lines.append(f"| {r['id']} | {cell(r['source'])} | {cell(r['severity'])} | {cell(r['layer'])} / {cell(r['owner'])} | "
                     f"**{r['status']}** | {cell(r['commit_fixed'])} | {cell(r['root_cause'])} | {tests} | "
                     f"{cell(r['shared_root_cause_ids'])} | {cell(r['limitations'])} |")
    return "\n".join(lines) + "\n"


def render_remediation(data: dict) -> str:
    rows = data["gaps"]
    counts = {s: sum(r["status"] == s for r in rows) for s in STATUSES}
    decisions = {d: sum(r["decision"] == d for r in rows) for d in DECISIONS}
    lines = [
        "# Remediation ledger — Assertiva 0.10.1 candidate",
        "",
        (f"Generated by [`scripts/gap_matrix.py`](../../scripts/gap_matrix.py) from [the JSON](REMEDIATION_0_10_1.json) "
        "(the source of truth; edit it, then re-run the script). Baseline: Assertiva 0.10.0 "
        f"`{data['baseline']}`. Inputs: {data['inputs']}"),
        "",
        (f"{len(rows)} rows: {len(REMEDIATION_INHERITED)} inherited from the Derivanta intakes (AXF-*, never renumbered) and "
        f"{len(rows) - len(REMEDIATION_INHERITED)} found during this round (DG-*)."),
        "",
        "Status: " + ", ".join(f"{s} {n}" for s, n in counts.items() if n) + ". "
        "Decision: " + ", ".join(f"{d} {n}" for d, n in decisions.items() if n) + ".",
        "",
        ("| ID | CP | Origin | Severity | Owner | Decision | Status | Commit | Expected / observed | Tests (before → after) | "
        "Negative controls | Related | Limitations / next |"),
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    cell = lambda v: (", ".join(v) if isinstance(v, list) else str(v or "")).replace("|", "\\|").replace("\n", " ")
    for r in rows:
        tests = f"{cell(r['test_before'])} → {cell(r['test_after'])}" if r["test_before"] or r["test_after"] else ""
        rest = cell(r["limitations"]) + (f" Next: {cell(r['next'])}" if r.get("next") else "")
        lines.append(f"| {r['id']} | {cell(r['checkpoint'])} | {cell(r['origin'])} | {cell(r['severity'])} | {cell(r['owner'])} | "
                     f"{r['decision']} | **{r['status']}** | {cell(r['commit_fixed'])} | expected: {cell(r['expected'])} — "
                     f"observed: {cell(r['observed'])} | {tests} | {cell(r['negative_controls'])} | "
                     f"{cell(r['shared_root_cause_ids'])} | {rest} |")
    ideas = data.get("ideas") or []
    if ideas:
        lines += ["", "## Ideas and external references (triage, not defects)", "",
                  "| ID | Idea | Source | Decision | Why |", "| --- | --- | --- | --- | --- |"]
        lines += [f"| {i['id']} | {cell(i['idea'])} | {cell(i['source'])} | {i['decision']} | {cell(i['why'])} |" for i in ideas]
    return "\n".join(lines) + "\n"


def _ledgers():
    yield DATA, VIEW, lambda d: problems(d["gaps"]), lambda d: render(d["gaps"])
    if REMEDIATION_DATA.is_file():
        yield (REMEDIATION_DATA, REMEDIATION_VIEW,
               lambda d: problems(d["gaps"], REMEDIATION_INHERITED, FIELDS + REMEDIATION_FIELDS), render_remediation)


def main(argv: list[str]) -> int:
    failed = False
    for data_path, view_path, check, draw in _ledgers():
        data = json.loads(data_path.read_text(encoding="utf-8"))
        found = check(data)
        for problem in found:
            print(f"{data_path.name}: {problem}", file=sys.stderr)
        view = draw(data)
        stale = not view_path.is_file() or view_path.read_text(encoding="utf-8") != view
        if "--check" in argv:
            if stale:
                print(f"{view_path.relative_to(ROOT)} is stale: run python scripts/gap_matrix.py", file=sys.stderr)
            failed |= bool(found) or stale
            continue
        view_path.write_text(view, encoding="utf-8", newline="\n")
        failed |= bool(found)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
